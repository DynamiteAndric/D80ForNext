"""Assemble the .d80 dot command sources with sjasmplus.

Step 1 (patches): dot/mdospatch.asm is assembled twice, once with every
image pre-filled with 0x00 and once with 0xFF. Bytes that are equal in both
builds are patch bytes; everything else is untouched ROM. The result is
written to dot/build/patches.json (used by d80tool.mdospatch) and
dot/build/patches.inc (included by the dot command), so no ROM content is
ever stored in the repository.

Step 2 (dot command): dot/d80.asm is assembled to dot/build/D80 if present.

    python tools/build_dot.py
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOT = ROOT / "dot"
BUILD = DOT / "build"
SJASM = ROOT / "tools" / "sjasmplus" / "sjasmplus-1.24.0.win" / "sjasmplus.exe"
IMAGES = {"mda": 0x0000, "mdb": 0x2000}  # name -> base address
DATA_SYMBOLS = ("img_secs", "page_table", "fix_pg2", "fix_pg7",
                "sd_on", "sd_n", "sd_cs", "sd_blk", "SD_MAP", "SD_MAX",
                "nr06_on", "nr06_off0", "nr06_off8",
                "sd_put", "op", "cur_lsn", "cur_buf",
                "snap_entry0_x", "snap_entry8_j", "page_out_j")  # from sd_put on: tests only


def sjasm(*args: str) -> None:
    if not SJASM.exists():
        sys.exit(f"sjasmplus not found at {SJASM}")
    r = subprocess.run([str(SJASM), "--nologo", "--msg=war", *args], cwd=DOT,
                       capture_output=True, text=True)
    if r.returncode or "error" in (r.stdout + r.stderr).lower():
        sys.exit(f"sjasmplus failed:\n{r.stdout}{r.stderr}")


def symbols(path: Path) -> dict[str, int]:
    out = {}
    for line in path.read_text().splitlines():
        m = re.match(r"(\w+): EQU 0x([0-9A-Fa-f]+)", line)
        if m:
            out[m.group(1)] = int(m.group(2), 16)
    return out


def runs(a: bytes, b: bytes) -> list[tuple[int, bytes]]:
    """Offsets where both fills agree, grouped into (offset, bytes) runs."""
    out: list[tuple[int, bytes]] = []
    i = 0
    while i < len(a):
        if a[i] != b[i]:
            i += 1
            continue
        j = i
        while j < len(a) and a[j] == b[j]:
            j += 1
        out.append((i, a[i:j]))
        i = j
    return out


def build_patches() -> dict:
    BUILD.mkdir(exist_ok=True)
    fills = {}
    for fill in (0, 255):
        sjasm(f"-DFILL={fill}", "--sym=build/mdospatch.sym", "mdospatch.asm")
        fills[fill] = {n: (BUILD / f"{n}.bin").read_bytes() for n in IMAGES}
    sym = symbols(BUILD / "mdospatch.sym")
    data = {"images": {}, "symbols": {k: sym[k] for k in DATA_SYMBOLS}}
    for name in IMAGES:
        data["images"][name] = [[off, blk.hex()] for off, blk in runs(fills[0][name], fills[255][name])]
    (BUILD / "patches.json").write_text(json.dumps(data, indent=1))
    write_inc(data)
    for n in IMAGES:
        (BUILD / f"{n}.bin").unlink()
    return data


def write_inc(data: dict) -> None:
    """Patch table for the dot command: per image, records `dw offset / db len / db bytes`."""
    lines = ["; generated by tools/build_dot.py from mdospatch.asm - do not edit", ""]
    for name, recs in data["images"].items():
        lines.append(f"patch_{name}:")
        for off, hx in recs:
            blk = bytes.fromhex(hx)
            for k in range(0, len(blk), 255):
                part = blk[k:k + 255]
                lines.append(f"    dw #{off + k:04X} : db {len(part)}")
                for p in range(0, len(part), 16):
                    lines.append("    db " + ",".join(f"#{x:02X}" for x in part[p:p + 16]))
        lines.append("    dw #FFFF")
    lines.append("")
    for k, v in data["symbols"].items():
        lines.append(f"MDB_{k.upper()} equ #{v:04X}")
    (BUILD / "patches.inc").write_text("\n".join(lines) + "\n")


def main() -> None:
    data = build_patches()
    n = sum(len(bytes.fromhex(h)) for recs in data["images"].values() for _, h in recs)
    print(f"patches: {n} bytes in {sum(len(r) for r in data['images'].values())} runs, "
          f"-> {BUILD / 'patches.json'}")
    if (DOT / "d80.asm").exists():
        sjasm("--sym=build/d80.sym", "--lst=build/d80.lst", "d80.asm")
        print(f"dot command: {BUILD / 'D80'} ({(BUILD / 'D80').stat().st_size} bytes)")


if __name__ == "__main__":
    main()
